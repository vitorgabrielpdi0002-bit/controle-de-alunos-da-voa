export function formatCurrency(value) {
  const num = Number(value) || 0;
  return num.toLocaleString('pt-BR', { style: 'currency', currency: 'BRL' });
}

export function formatDate(dateString) {
  if (!dateString) return '-';
  const parts = dateString.split('-');
  if (parts.length === 3) {
    return `${parts[2]}/${parts[1]}/${parts[0]}`;
  }
  return dateString;
}

export function formatMonthName(monthRef) {
  if (!monthRef) return '';
  const [year, month] = monthRef.split('-');
  const months = ['Janeiro', 'Fevereiro', 'Março', 'Abril', 'Maio', 'Junho', 'Julho', 'Agosto', 'Setembro', 'Outubro', 'Novembro', 'Dezembro'];
  const monthName = months[parseInt(month, 10) - 1] || month;
  return `${monthName} de ${year}`;
}

export function renderCategoryBadge(categoryId) {
  const cat = getCategoryById(categoryId);
  return `
    <span class="category-badge" style="background: ${cat.bg}; color: ${cat.color}; border: 1px solid ${cat.color}40;">
      <span style="width: 7px; height: 7px; border-radius: 50%; background: ${cat.color};"></span>
      ${cat.name}
    </span>
  `;
}

export function getInitials(name) {
  if (!name) return 'AT';
  const parts = name.trim().split(' ');
  if (parts.length === 1) return parts[0].slice(0, 2).toUpperCase();
  return (parts[0][0] + parts[parts.length - 1][0]).toUpperCase();
}

export function getWhatsAppUrl(phone, message = '') {
  if (!phone) return '#';
  const cleanPhone = phone.replace(/\D/g, '');
  const ddi = cleanPhone.length <= 11 ? '55' : '';
  const encoded = encodeURIComponent(message);
  return `https://wa.me/${ddi}${cleanPhone}?text=${encoded}`;
}

// Modal Controllers
export function openModal(modalId) {
  const modal = document.getElementById(modalId);
  if (modal) {
    modal.classList.add('active');
    document.body.style.overflow = 'hidden';
  }
}

export function closeModal(modalId) {
  const modal = document.getElementById(modalId);
  if (modal) {
    modal.classList.remove('active');
    document.body.style.overflow = '';
  }
}

// Toast Notifications
export function showToast(message, type = 'success') {
  const container = document.getElementById('toastContainer');
  if (!container) return;

  const toast = document.createElement('div');
  toast.className = `toast ${type}`;
  toast.innerHTML = `
    <span>${type === 'success' ? ICONS.check : ICONS.alertCircle}</span>
    <span>${message}</span>
  `;
  container.appendChild(toast);

  setTimeout(() => {
    toast.style.opacity = '0';
    toast.style.transform = 'translateX(30px)';
    toast.style.transition = 'all 0.3s ease';
    setTimeout(() => toast.remove(), 300);
  }, 3500);
}
